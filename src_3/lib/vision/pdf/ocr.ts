
import { execFile } from "node:child_process";
import {
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { promisify } from "node:util";

import type { PdfTextItem } from "./text";

const execFileAsync = promisify(execFile);

interface TesseractWord {
  text: string;
  left: number;
  top: number;
  width: number;
  height: number;
  confidence: number;
}

/**
 * Run native Tesseract OCR on a rendered PDF image.
 *
 * Requires Tesseract to be installed on the machine:
 *
 *   brew install tesseract
 *
 * Verify with:
 *
 *   which tesseract
 *   tesseract --version
 *
 * This implementation intentionally does NOT use tesseract.js.
 */
export async function ocrPdfImage(
  image: Buffer,
): Promise<PdfTextItem[]> {
  const tempDir = await mkdtemp(
    path.join(
      tmpdir(),
      "buildflow-ocr-",
    ),
  );

  const inputPath = path.join(
    tempDir,
    "page.png",
  );

  const outputBase = path.join(
    tempDir,
    "ocr",
  );

  const outputTsv =
    `${outputBase}.tsv`;

  try {
    /*
     * Save the rendered PDF page.
     */
    await writeFile(
      inputPath,
      image,
    );

    /*
     * Run native Tesseract.
     *
     * --psm 11:
     * Sparse text. This is generally useful for floor plans
     * because text can appear in many separate locations.
     *
     * TSV:
     * Gives us text + bounding boxes.
     */
    await execFileAsync(
      "tesseract",
      [
        inputPath,
        outputBase,
        "-l",
        "eng",
        "--psm",
        "11",
        "tsv",
      ],
      {
        maxBuffer:
          20 * 1024 * 1024,
      },
    );

    /*
     * Read TSV generated by Tesseract.
     */
    const tsv =
      await readFile(
        outputTsv,
        "utf8",
      );

    const words =
      parseTesseractTsv(tsv);

    console.log(
      `Tesseract OCR detected ${words.length} text items.`,
    );

    /*
     * Convert Tesseract coordinates into PdfTextItem.
     *
     * Tesseract:
     *   left/top = top-left origin
     *
     * PdfTextItem:
     *   position = center of text bounding box
     */
    return words.map(
      (word) => ({
        text: word.text,

        position: [
          word.left +
            word.width / 2,

          word.top +
            word.height / 2,
        ],

        width:
          word.width,

        height:
          word.height,
      }),
    );
  } catch (error) {
    const message =
      error instanceof Error
        ? error.message
        : String(error);

    console.error(
      "Native Tesseract OCR failed:",
      message,
    );

    throw new Error(
      `Tesseract OCR failed: ${message}`,
    );
  } finally {
    /*
     * Remove temporary files even when OCR fails.
     */
    await rm(
      tempDir,
      {
        recursive: true,
        force: true,
      },
    );
  }
}

/**
 * Parse Tesseract TSV output.
 *
 * TSV format:
 *
 * level
 * page_num
 * block_num
 * par_num
 * line_num
 * word_num
 * left
 * top
 * width
 * height
 * conf
 * text
 */
function parseTesseractTsv(
  tsv: string,
): TesseractWord[] {
  const lines =
    tsv.split(/\r?\n/);

  if (lines.length <= 1) {
    return [];
  }

  const result: TesseractWord[] =
    [];

  /*
   * Skip the TSV header.
   */
  for (
    let i = 1;
    i < lines.length;
    i++
  ) {
    const line =
      lines[i];

    if (!line.trim()) {
      continue;
    }

    const columns =
      line.split("\t");

    /*
     * A normal Tesseract TSV word row has
     * at least 12 columns.
     */
    if (
      columns.length < 12
    ) {
      continue;
    }

    const left =
      Number(columns[6]);

    const top =
      Number(columns[7]);

    const width =
      Number(columns[8]);

    const height =
      Number(columns[9]);

    const confidence =
      Number(columns[10]);

    const text =
      columns
        .slice(11)
        .join("\t")
        .trim();

    /*
     * Ignore rows without text.
     */
    if (!text) {
      continue;
    }

    /*
     * Ignore invalid bounding boxes.
     */
    if (
      !Number.isFinite(left) ||
      !Number.isFinite(top) ||
      !Number.isFinite(width) ||
      !Number.isFinite(height)
    ) {
      continue;
    }

    result.push({
      text,
      left,
      top,
      width,
      height,
      confidence:
        Number.isFinite(
          confidence,
        )
          ? confidence
          : 0,
    });
  }

  return result;
}
